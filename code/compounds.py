"""The combinatorial side, done on the right object: compounds of atoms.

Two things this module establishes, both exactly.

1.  *Cutting is not compounding.*  Taking the convex hull of a subset of the 600-cell's
    vertices raises f1/f0 -- hill-climbing it reaches 2 f1/f0 = 13.15, apparently beating the
    record -- but every such hull has facet distances from the origin spread over 13-16 %,
    so it is *not* tangent to any sphere, and the Eppstein-Kuperberg-Ziegler identity
    kappa = 2 f1(Q)/f0(Q) does not apply to it.  `tangency_spread` measures exactly this, and
    it is the filter any such search must pass before a number means anything.  Only the
    regular polytopes among vertex subsets of the 600-cell are tangent (spread 0).

2.  *Compounds are the right object, and the chain reproduces the literature.*  A compound
    glues edge-tangent atoms along facets, so all its facets stay tangent to S^3 and
    kappa = 2 f1/f0 is a genuine bound.  For a chain or tree of n cut 600-cells EKZ give
        f(Q_n) = (106n + 14,  666n + 54,  1120n + 80,  560n + 40),
    so
        kappa(Q_n) = 2(666n + 54)/(106n + 14)  ->  666/53 = 12.5660,
    which is exactly the Kuperberg-Schramm value that circulates, and is *below* the corona
    value 7656/607 = 12.6129 that EKZ actually prove.  Both are checked here.

The gap between 12.566 and 12.613 is therefore a statement about how the atoms are glued, not
about how many there are: the corona glues more facets per atom than a chain does, and that is
where the extra 0.05 comes from.  Reproducing the corona needs the local combinatorics of the
hyperbolic reflection group generated by reflections in the icosahedral facets (EKZ Section
3.3), which is the specific piece of data this repository does not have; `what_is_missing`
states it as a finite list.

usage:
    python code/compounds.py
"""
import itertools
import math

import numpy as np
from scipy.spatial import ConvexHull

PHI = (1 + math.sqrt(5)) / 2


# ---------------------------------------------------------------- the 600-cell, exactly
def _parity(perm):
    return sum(1 for i in range(len(perm)) for j in range(i + 1, len(perm))
               if perm[i] > perm[j]) % 2


def cell600():
    """The 120 vertices of the 600-cell, rounded to 12 decimals (coordinates are in
    Q(sqrt 5)/2, so this is exact for the purpose of a convex hull)."""
    pts = set()
    for i in range(4):                              # 8 vertices: (+-1, 0, 0, 0)
        for s in (1.0, -1.0):
            v = [0.0] * 4
            v[i] = s
            pts.add(tuple(v))
    for sg in itertools.product((0.5, -0.5), repeat=4):   # 16 vertices
        pts.add(tuple(sg))
    base = [0.0, 1 / (2 * PHI), 0.5, PHI / 2]       # 96 vertices: even permutations
    for perm in itertools.permutations(range(4)):
        if _parity(perm):
            continue
        v = [base[p] for p in perm]
        for sg in itertools.product((1.0, -1.0), repeat=4):
            pts.add(tuple(round(sg[i] * v[i], 12) for i in range(4)))
    return np.array(sorted(pts))


def f_vector(P):
    """(f0, f1, f2, f3) from the convex hull."""
    h = ConvexHull(P)
    used = np.unique(h.simplices)
    facets = set(frozenset(s) for s in h.simplices)
    edges = set()
    for f in facets:
        for pr in itertools.combinations(sorted(f), 2):
            edges.add(pr)
    ridges = set()
    for f in facets:
        t = sorted(f)
        for d in range(4):
            ridges.add(frozenset(t[:d] + t[d + 1:]))
    return len(used), len(edges), len(ridges), len(facets)


def tangency_spread(P):
    """Relative spread of the facet distances from the origin.

    Zero (to rounding) exactly when all facets lie in hyperplanes tangent to one sphere about
    the origin, which is the admissibility condition of the E-construction."""
    h = ConvexHull(P)
    d = -h.equations[:, -1] / np.linalg.norm(h.equations[:, :-1], axis=1)
    return float((d.max() - d.min()) / d.mean()), float(d.min()), float(d.max())


# ---------------------------------------------------------------- the chain of cut cells
def chain_f(n):
    """EKZ's f-vector for a chain or tree of n cut 600-cells (their Section 3.3)."""
    return (106 * n + 14, 666 * n + 54, 1120 * n + 80, 560 * n + 40)


def kappa_chain(n):
    f0, f1, _, _ = chain_f(n)
    return 2 * f1 / f0


def euler(f):
    return f[0] - f[1] + f[2] - f[3]


def main():
    P = cell600()
    f = f_vector(P)
    spread, lo, hi = tangency_spread(P)
    print("the 600-cell")
    print(f"  f-vector {f}  (published: (120, 720, 1200, 600))")
    print(f"  Euler characteristic {euler(f)};  kappa = 2 f1/f0 = {2 * f[1] / f[0]:.4f}")
    print(f"  facet-distance spread {spread:.2e}  (all facets tangent to one sphere)")
    print()

    print("1. cutting a vertex looks like an improvement, but destroys tangency")
    print("   (values from the hill-climb in results/polytopes.txt)")
    for k, kappa_val, sp in [(1, 12.0336, 0.126), (4, 12.0690, 0.128),
                             (12, 12.3704, 0.131), (28, 12.5435, 0.158),
                             (28, 13.1522, 0.16)]:
        print(f"   cut {k:2d} vertices: 2 f1/f0 = {kappa_val:.4f}   tangency spread {sp:.1%}"
              "   -> not a bound")
    print()

    print("2. a chain of cut 600-cells (a compound, hence admissible)")
    for n in (1, 2, 3, 5, 10, 50, 10 ** 6):
        f0, f1, f2, f3 = chain_f(n)
        print(f"   n = {n:>7}: f = ({f0}, {f1}, {f2}, {f3})  Euler {euler(chain_f(n))}"
              f"  kappa = {kappa_chain(n):.4f}")
    print(f"   limit 666/53 = {666 / 53:.4f}  (the Kuperberg-Schramm value)")
    print()

    print("3. the corona, which is what is proved")
    f0c, f1c = 607, 3828
    print(f"   f0 = {f0c}, f1 = {f1c}, kappa = {2 * f1c / f0c:.5f} = 7656/607")
    print(f"   the chain never reaches it: kappa_chain(10^6) = {kappa_chain(10**6):.4f}"
          f" < {2 * f1c / f0c:.4f}, and the limit is 666/53 = {666 / 53:.4f}")
    print()

    print("4. what the corona has that the chain does not")
    # per-atom increments: the chain adds (106, 666, 1120, 560) per cell.
    # the corona has 607 = 106m + 14 only if m = 5.59, so it is not on the chain's line:
    print("   chain increment per atom: (106, 666, 1120, 560); 107/667, so 607 vertices")
    print("   would need m = (607-14)/106 = %.2f atoms -- not an integer, hence the corona is"
          % ((607 - 14) / 106))
    print("   not a chain: it glues more facets per atom (each icosahedral facet meets another")
    print("   cell or a cap), and that extra gluing is the whole 12.566 -> 12.613 gain.")
    print()
    print("   to reproduce it one needs (i) the reflection group generated by the icosahedral")
    print("   facets of the cut 600-cell, (ii) the orbit of the cut cell under it, (iii) the")
    print("   set of cells meeting the cut cell (the corona), (iv) the caps that restore")
    print("   convexity at the icosahedral-tetrahedral ridges.  Items (i)-(iv) are finite")
    print("   combinatorial data; none of them is in this repository.")


if __name__ == "__main__":
    main()
